#!/usr/bin/env node
/**
 * Generates the `location_lookup` INSERT statement for
 * 20260909000000_map_location_lookup.sql from location-lookup-data.mjs —
 * mirrors migration/nhtsa/build-import-sql.mjs's existing pattern (generate
 * from a reviewable data file, never hand-retype SQL literals that must stay
 * in sync with it).
 *
 * Run: node migration/map/build-location-lookup-sql.mjs
 * Paste the output into the migration's location_lookup INSERT.
 */
import { COUNTRIES, REGIONS, CITIES } from "./location-lookup-data.mjs";

function sqlString(value) {
  if (value === null || value === undefined) return "null";
  return `'${String(value).replace(/'/g, "''")}'`;
}

function keyFor(row) {
  if (row.level === "country") return row.countryCode.toUpperCase();
  if (row.level === "region") return `${row.regionCode.toUpperCase()}|${row.countryCode.toUpperCase()}`;
  // city
  return row.regionCode
    ? `${row.cityName.toUpperCase()}|${row.regionCode.toUpperCase()}|${row.countryCode.toUpperCase()}`
    : `${row.cityName.toUpperCase()}|${row.countryCode.toUpperCase()}`;
}

const allRows = [...COUNTRIES, ...REGIONS, ...CITIES];
const keys = new Set();
for (const row of allRows) {
  const key = keyFor(row);
  if (keys.has(key)) throw new Error(`Duplicate location_lookup key: ${key}`);
  keys.add(key);
}

const lines = allRows.map((row) => {
  const key = keyFor(row);
  return (
    `  (${sqlString(key)}, ${sqlString(row.level)}, ${sqlString(row.countryCode)}, ` +
    `${sqlString(row.regionCode ?? null)}, ${sqlString(row.cityName ?? null)}, ` +
    `${row.latitude}, ${row.longitude}, ${sqlString(row.displayName)})`
  );
});

console.log(`-- Generated by migration/map/build-location-lookup-sql.mjs from location-lookup-data.mjs.`);
console.log(`-- Do not hand-edit these VALUES; edit the data file and regenerate.`);
console.log(`insert into public.location_lookup`);
console.log(`  (key, level, country_code, region_code, city_name, latitude, longitude, display_name)`);
console.log(`values`);
console.log(lines.join(",\n") + ";");
console.log();
console.error(`Generated ${allRows.length} rows (${COUNTRIES.length} countries, ${REGIONS.length} regions, ${CITIES.length} cities).`);
